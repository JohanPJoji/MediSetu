"""
safety.py — Deterministic red-flag / medical emergency detection.

This module runs BEFORE every Gemini API call in the intake flow.
Detection is done with compiled regex patterns — NOT delegated to the LLM.

Clinical rationale for the included conditions:
  - Chest pain + associated descriptors: ACS / MI
  - Difficulty breathing / dyspnea: PE, severe asthma, anaphylaxis
  - Stroke FAST symptoms: Facial drooping, Arm weakness, Speech difficulty, Time
  - Severe bleeding / uncontrolled haemorrhage
  - Loss of consciousness / syncope
  - Anaphylaxis signs: throat swelling, hives + breathing difficulty
  - Suicidal ideation / self-harm intent
  - Seizure / convulsion
  - Severe allergic reaction to known allergen
  - Sudden severe headache ("thunderclap"): subarachnoid haemorrhage
  - High fever in infant / meningism signs

NOTE: This list is a clinically-informed starting point.
Have a qualified clinician review and expand it before go-live.
"""

from __future__ import annotations

import re
from dataclasses import dataclass


# ──────────────────────────────────────────────────────────────────────────────
# Emergency response — fixed, deterministic, NOT generated by LLM
# ──────────────────────────────────────────────────────────────────────────────

EMERGENCY_RESPONSE = (
    "⚠️ IMPORTANT: Based on what you've described, you may need IMMEDIATE medical attention. "
    "Please do NOT wait — tell the nearest hospital staff RIGHT NOW, or call emergency services (112 / 108). "
    "If you are alone, call someone for help immediately. "
    "Do not fill in the rest of this form — go to the Emergency department now."
)

EMERGENCY_VOICE_RESPONSE = (
    "Important alert. Based on what you described, you may need immediate medical attention. "
    "Please tell the nearest hospital staff right now, or call emergency services. "
    "Do not continue with this form. Go to the emergency department immediately."
)


# ──────────────────────────────────────────────────────────────────────────────
# Red-flag patterns (compiled once at import time)
# ──────────────────────────────────────────────────────────────────────────────

_RAW_PATTERNS: list[tuple[str, str]] = [
    # ── Cardiac ──────────────────────────────────────────────────────────────
    ("chest_pain_crushing", r"\b(crushing|squeezing|pressure|tightness|heaviness)\b.{0,40}\bchest\b"),
    ("chest_pain_general", r"\bchest\b.{0,30}\b(pain|ache|hurt|tight|pressure)\b"),
    ("chest_pain_radiating", r"\bpain\b.{0,40}\b(jaw|left arm|shoulder|neck)\b"),
    ("palpitations_severe", r"\b(heart racing|heart pounding|heart skipping|palpitation).{0,20}(faint|dizzy|pass out|collapse)\b"),

    # ── Respiratory ──────────────────────────────────────────────────────────
    ("difficulty_breathing", r"\b(can'?t breathe|cannot breathe|difficulty breath|hard to breathe|shortness of breath|short of breath|struggling to breathe|not able to breathe)\b"),
    ("breathing_severe", r"\b(no breath|stop breathing|breath stopped)\b"),

    # ── Stroke (FAST) ────────────────────────────────────────────────────────
    ("facial_drooping", r"\b(face drooping|facial droop|face droop|one side of (my |the )?face|half my face)\b"),
    ("arm_weakness_sudden", r"\b(sudden(ly)?|can'?t lift).{0,20}\b(arm|hand)\b.{0,20}\b(weak|numb|drooping)\b"),
    ("slurred_speech", r"\b(slurred? speech|can'?t speak|speech difficult|trouble speaking|words (not coming|jumbled|confused))\b"),
    ("one_sided_weakness", r"\b(one(?: |-)sided|one side of (my |the )?(body|face|arm|leg)|hemiplegia|hemiparesis)\b"),
    ("sudden_severe_headache", r"\b(worst headache|sudden(ly)?.{0,20}(severe|extreme|terrible).{0,20}headache|thunderclap headache|headache.{0,20}never had before)\b"),

    # ── Bleeding ─────────────────────────────────────────────────────────────
    ("severe_bleeding", r"\b(severe bleeding|heavy bleeding|uncontrolled bleeding|bleeding (won'?t|doesn'?t|not) stop|blood everywhere|spurting blood|large amount of blood)\b"),
    ("coughing_blood", r"\b(cough(ing)? (up )?blood|vomit(ing)? blood|blood in (vomit|stool|urine|sputum))\b"),

    # ── Consciousness ────────────────────────────────────────────────────────
    ("loss_of_consciousness", r"\b(passed out|fainted|loss of consciousness|unconscious|blacked out|collapse[sd]|fell unconscious)\b"),
    ("seizure", r"\b(seizure|convulsion|fit|epileptic|shaking uncontrollabl)\b"),

    # ── Anaphylaxis ──────────────────────────────────────────────────────────
    ("throat_swelling", r"\b(throat (swelling|closing|tightening|swollen)|tongue swelling|swollen tongue|can'?t swallow|difficulty swallowing.{0,20}breath)\b"),
    ("anaphylaxis_signs", r"\b(allergic reaction.{0,30}(bad|severe|serious)|severe allergic|anaphyla[xs]is)\b"),

    # ── Suicidal / self-harm ─────────────────────────────────────────────────
    ("suicidal_ideation", r"\b(want to (die|kill myself|end my life)|thinking about (suicide|killing myself|ending it)|suicidal|self.harm|hurt myself|no reason to live)\b"),

    # ── Paediatric ───────────────────────────────────────────────────────────
    ("infant_fever_high", r"\b(baby|infant|newborn).{0,40}(very high fever|40 degree|41 degree|104 f|105 f)\b"),
    ("meningism", r"\b(stiff neck.{0,30}(fever|headache)|neck rigidity|meningitis|meningism|can'?t bend.{0,20}neck)\b"),

    # ── Poisoning / overdose ─────────────────────────────────────────────────
    ("overdose", r"\b(overdose|too many (tablet|pill|capsule|medicine)|swallowed (a lot of|too much).{0,30}(medicine|tablet|pill))\b"),
    ("poisoning", r"\b(poison(ed|ing)|ingested.{0,20}(chemical|toxic|bleach|acid|pesticide))\b"),
]

# Compile all patterns (case-insensitive, multiline)
_COMPILED_PATTERNS: list[tuple[str, re.Pattern]] = [
    (name, re.compile(pattern, re.IGNORECASE | re.DOTALL))
    for name, pattern in _RAW_PATTERNS
]


# ──────────────────────────────────────────────────────────────────────────────
# Public API
# ──────────────────────────────────────────────────────────────────────────────

@dataclass
class RedFlagResult:
    is_emergency: bool
    matched_pattern: str | None      # Name of the first pattern that matched
    emergency_message: str | None    # Fixed response text (never LLM-generated)
    voice_message: str | None        # Shorter version for TTS


def check_for_emergency(text: str) -> RedFlagResult:
    """
    Run all red-flag patterns against the input text.

    This is deterministic code — the LLM plays NO role in this decision.
    Returns a RedFlagResult; if is_emergency is True the caller MUST
    short-circuit and return the fixed emergency response without calling Gemini.

    Args:
        text: Raw patient input (text transcript or STT output).

    Returns:
        RedFlagResult with is_emergency=True if any pattern matches.
    """
    if not text or not text.strip():
        return RedFlagResult(is_emergency=False, matched_pattern=None, emergency_message=None, voice_message=None)

    for name, pattern in _COMPILED_PATTERNS:
        if pattern.search(text):
            return RedFlagResult(
                is_emergency=True,
                matched_pattern=name,
                emergency_message=EMERGENCY_RESPONSE,
                voice_message=EMERGENCY_VOICE_RESPONSE,
            )

    return RedFlagResult(is_emergency=False, matched_pattern=None, emergency_message=None, voice_message=None)


def get_pattern_names() -> list[str]:
    """Return list of all pattern names — useful for testing coverage."""
    return [name for name, _ in _COMPILED_PATTERNS]
